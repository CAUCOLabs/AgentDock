from datetime import datetime, timezone
from pathlib import Path
import shlex
import subprocess
from time import perf_counter

from app.config import Settings
from app.models import AgentProvider


class AgentRunnerError(Exception):
    """
    Raised when an agent runner operation fails.
    """


class AgentRunResult:
    """
    Result returned after an agent has attempted to apply a task.
    """

    def __init__(
        self,
        success: bool,
        message: str,
        modified_files: list[str] | None = None,
        stdout: str = "",
        stderr: str = "",
        exit_code: int | None = None,
        duration_seconds: float | None = None,
    ) -> None:
        self.success = success
        self.message = message
        self.modified_files = modified_files or []
        self.stdout = stdout
        self.stderr = stderr
        self.exit_code = exit_code
        self.duration_seconds = duration_seconds

    def log_messages(self) -> list[tuple[str, str]]:
        """
        Return concise task log entries for runner diagnostics.
        """

        messages: list[tuple[str, str]] = []

        if self.duration_seconds is not None:
            messages.append(("info", f"Runner duration: {self.duration_seconds:.2f}s."))

        if self.exit_code is not None:
            level = "info" if self.exit_code == 0 else "error"
            messages.append((level, f"Runner exit code: {self.exit_code}."))

        if self.stdout.strip():
            messages.append(("info", f"Runner stdout:\n{self.stdout.strip()}"))

        if self.stderr.strip():
            level = "info" if self.success else "error"
            messages.append((level, f"Runner stderr:\n{self.stderr.strip()}"))

        return messages


class BaseAgentRunner:
    """
    Base interface for coding agent runners.
    """

    def run(
        self,
        repo_path: Path,
        instruction: str,
    ) -> AgentRunResult:
        """
        Run the agent against a repository path.
        """

        raise NotImplementedError


class MockRunner(BaseAgentRunner):
    """
    Safe mock agent for MVP development.

    This runner does not call any external AI service.
    It writes a deterministic task note into the repository so we can test:

    - workspace creation
    - repo changes
    - diff generation
    - approval workflow
    - later commit/push flow
    """

    TASK_NOTES_FILE = "AGENTDOCK_TASK.md"

    def run(
        self,
        repo_path: Path,
        instruction: str,
    ) -> AgentRunResult:
        """
        Apply a deterministic mock change to the repository.
        """

        if not repo_path.exists() or not repo_path.is_dir():
            raise AgentRunnerError(f"Repository path does not exist: {repo_path}")

        note_path = repo_path / self.TASK_NOTES_FILE
        timestamp = datetime.now(timezone.utc).isoformat()

        content = self._build_task_note(
            instruction=instruction,
            timestamp=timestamp,
        )

        try:
            note_path.write_text(content, encoding="utf-8")
        except OSError as exc:
            raise AgentRunnerError(
                f"Failed to write mock agent output: {note_path}"
            ) from exc

        return AgentRunResult(
            success=True,
            message="Mock agent completed successfully.",
            modified_files=[self.TASK_NOTES_FILE],
        )

    def _build_task_note(
        self,
        instruction: str,
        timestamp: str,
    ) -> str:
        """
        Build deterministic markdown content for the mock agent output.
        """

        return (
            "# AgentDock Task Note\n\n"
            "This file was generated by the AgentDock mock agent runner.\n\n"
            "## Instruction\n\n"
            f"{instruction.strip()}\n\n"
            "## Status\n\n"
            "- Provider: mock\n"
            "- Result: completed\n"
            f"- Timestamp: {timestamp}\n\n"
            "## Next Step\n\n"
            "Review the generated diff before approving any commit.\n"
        )


