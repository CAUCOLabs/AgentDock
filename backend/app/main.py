from datetime import datetime, timezone

from fastapi import Depends, FastAPI, HTTPException, status

from app.config import Settings, get_settings
from app.models import (
    ChangedFile,
    TaskApprovalRequest,
    TaskApprovalResponse,
    TaskCreateRequest,
    TaskCreateResponse,
    TaskDiffResponse,
    TaskStatus,
    TaskSummary,
    create_task_id,
    create_working_branch,
)

app = FastAPI(
    title="AgentDock API",
    description="Mobile-first command center for AI coding agents.",
    version="0.1.0",
)

# In-memory task store for the MVP bootstrap.
# Later this will move to a real database.
TASKS: dict[str, TaskSummary] = {}
TASK_DIFFS: dict[str, str] = {}


@app.get("/health")
def health(settings: Settings = Depends(get_settings)) -> dict[str, str | bool]:
    """
    Basic health endpoint.
    """

    return {
        "status": "ok",
        "app": settings.app_name,
        "env": settings.app_env,
        "debug": settings.app_debug,
    }


@app.get("/")
def root() -> dict[str, str]:
    """
    Root endpoint.
    """

    return {
        "message": "AgentDock API is running",
        "docs": "/docs",
        "health": "/health",
    }


@app.post(
    "/tasks",
    response_model=TaskCreateResponse,
    status_code=status.HTTP_201_CREATED,
)
def create_task(payload: TaskCreateRequest) -> TaskCreateResponse:
    """
    Create a new agent task.

    For now this creates a mock task and stores it in memory.
    The real task runner will be connected later.
    """

    now = datetime.now(timezone.utc)
    task_id = create_task_id()
    working_branch = create_working_branch(task_id)

    task = TaskSummary(
        task_id=task_id,
        repo_url=str(payload.repo_url),
        base_branch=payload.base_branch,
        working_branch=working_branch,
        instruction=payload.instruction,
        agent=payload.agent,
        status=TaskStatus.waiting_for_approval,
        changed_files=[
            ChangedFile(
                path="README.md",
                status="modified",
                additions=3,
                deletions=1,
            )
        ],
        created_at=now,
        updated_at=now,
    )

    TASKS[task_id] = task
    TASK_DIFFS[task_id] = (
        "diff --git a/README.md b/README.md\n"
        "index 0000000..1111111 100644\n"
        "--- a/README.md\n"
        "+++ b/README.md\n"
        "@@ -1,3 +1,5 @@\n"
        " # AgentDock\n"
        "-Early project draft.\n"
        "+Mobile-first command center for AI coding agents.\n"
        "+\n"
        "+Generated by the mock AgentDock task runner.\n"
    )

    return TaskCreateResponse(
        task_id=task_id,
        status=task.status,
        message="Task created. Mock diff is ready for review.",
    )


@app.get("/tasks", response_model=list[TaskSummary])
def list_tasks() -> list[TaskSummary]:
    """
    List all tasks currently stored in memory.
    """

    return list(TASKS.values())


@app.get("/tasks/{task_id}", response_model=TaskSummary)
def get_task(task_id: str) -> TaskSummary:
    """
    Get a task by id.
    """

    task = TASKS.get(task_id)

    if task is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Task not found: {task_id}",
        )

    return task


@app.get("/tasks/{task_id}/diff", response_model=TaskDiffResponse)
def get_task_diff(task_id: str) -> TaskDiffResponse:
    """
    Get the generated diff for a task.
    """

    task = TASKS.get(task_id)

    if task is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Task not found: {task_id}",
        )

    return TaskDiffResponse(
        task_id=task_id,
        status=task.status,
        diff=TASK_DIFFS.get(task_id, ""),
        changed_files=task.changed_files,
    )


@app.post("/tasks/{task_id}/approval", response_model=TaskApprovalResponse)
def approve_or_reject_task(
    task_id: str,
    payload: TaskApprovalRequest,
) -> TaskApprovalResponse:
    """
    Approve or reject a task.

    For now this only changes the task status in memory.
    Commit, push, and PR creation will be added later.
    """

    task = TASKS.get(task_id)

    if task is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Task not found: {task_id}",
        )

    now = datetime.now(timezone.utc)

    if payload.approve:
        task.status = TaskStatus.approved
        message = payload.message or "Task approved."
    else:
        task.status = TaskStatus.rejected
        message = payload.message or "Task rejected."

    task.updated_at = now
    TASKS[task_id] = task

    return TaskApprovalResponse(
        task_id=task_id,
        status=task.status,
        message=message,
    )